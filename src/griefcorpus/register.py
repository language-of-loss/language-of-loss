import csv
import json
import re
from collections import Counter
from pathlib import Path

import yaml

from .http import ROOT

EVID = ROOT / "data" / "discovery" / "evidence"
DOCS = ROOT / "docs"
NO_EVIDENCE_NEEDED = ("platform", "web")

COLUMNS = ["status", "material_type", "title", "url", "doi", "paper", "languages", "genre", "reported_size",
           "verified_size", "personal_bereavement", "dates_context", "population_evidence", "license",
           "restrictions", "auth_or_payment", "suitability", "limitations", "inspected", "api_http_status",
           "evidence_file", "verified_at"]
STATUS_ORDER = ["candidate", "candidate_with_caveats", "blocked_on_access", "restricted", "unresolved",
                "reference_only", "not_suitable"]


def evidence_path(key):
    platform, cid = key.split("::", 1)
    return EVID / (f"{platform}__" + re.sub(r"[^A-Za-z0-9._-]+", "_", cid)[:120] + ".json")


def build():
    dec = yaml.safe_load((ROOT / "config" / "source_decisions.yaml").read_text(encoding="utf-8"))
    shortlist = yaml.safe_load((ROOT / "config" / "shortlist.yaml").read_text(encoding="utf-8"))["candidates"]
    rows, problems = [], []
    for s in dec["sources"]:
        platform = s["key"].split("::", 1)[0]
        ev_file, ev = evidence_path(s["key"]), {}
        if platform not in NO_EVIDENCE_NEEDED:
            if not ev_file.exists():
                problems.append(f"NO EVIDENCE FILE for {s['key']} -- row dropped")
                continue
            ev = json.loads(ev_file.read_text(encoding="utf-8"))
        row = {c: s.get(c, "") for c in COLUMNS}
        row["languages"] = "; ".join(map(str, s.get("languages", []))) or "unknown"
        row["population_evidence"] = s.get("population_evidence") or "unknown"
        row["api_http_status"] = ev.get("api_status", "")
        row["evidence_file"] = str(ev_file.relative_to(ROOT)) if ev else "logs/requests.jsonl"
        row["verified_at"] = ev.get("verified_at", dec["inspected_on"])
        rows.append(row)
    decided = {s["key"] for s in dec["sources"]} | {k for s in dec["sources"] for k in s.get("also_covers", [])}
    for c in shortlist:
        k = f"{c['platform']}::{c['id']}"
        if k not in decided:
            problems.append(f"shortlisted but no decision recorded: {k}")
    rows.sort(key=lambda r: (STATUS_ORDER.index(r["status"]), r["material_type"], r["title"]))

    DOCS.mkdir(exist_ok=True)
    with (DOCS / "source_register.csv").open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=COLUMNS)
        w.writeheader()
        w.writerows(rows)

    log = list(csv.DictReader((ROOT / "data" / "discovery" / "search_log.csv").open(encoding="utf-8")))
    ncand = sum(1 for _ in (ROOT / "data" / "discovery" / "candidates.jsonl").open(encoding="utf-8"))
    per_platform = Counter()
    for r in log:
        per_platform[r["platform"]] += int(r["n_results"])
    md = ["# Stage 1 source register", "",
          f"Inspected on {dec['inspected_on']}. Generated by `python -m griefcorpus.register`; do not edit by hand.", "",
          "## How this was produced", "",
          f"- {len(log)} logged API searches on {len(per_platform)} platforms "
          f"({', '.join(f'{p}: {n} hits' for p, n in sorted(per_platform.items()))}) "
          f"-> {ncand} unique candidates (`data/discovery/candidates.jsonl`).",
          f"- {len(shortlist)} candidates shortlisted for file-level verification (`config/shortlist.yaml`); "
          f"evidence in `data/discovery/evidence/`.",
          f"- {len(rows)} register rows. Every HTTP request is in `logs/requests.jsonl` with status and SHA-256 of the body.",
          "", "## Status summary", ""]
    sc = Counter(r["status"] for r in rows)
    md += [f"- **{s}**: {sc[s]}" for s in STATUS_ORDER if sc[s]]
    md += ["", "## Material-type summary", ""]
    md += [f"- {m}: {n}" for m, n in Counter(r["material_type"] for r in rows).most_common()]
    for status in STATUS_ORDER:
        block = [r for r in rows if r["status"] == status]
        if not block:
            continue
        md += ["", f"## {status} ({len(block)})", ""]
        for r in block:
            md += [f"### {r['title']}", "",
                   f"- **URL:** {r['url']}" + (f" - DOI {r['doi']}" if r["doi"] else ""),
                   *([f"- **Paper:** {r['paper']}"] if r["paper"] else []),
                   f"- **Type:** {r['material_type']} - **Languages:** {r['languages']} - **Genre:** {r['genre'] or 'n/a'}",
                   f"- **Reported size:** {r['reported_size'] or 'not reported'}",
                   f"- **Verified accessible size:** {r['verified_size'] or 'not verified'}",
                   f"- **Personal bereavement:** {r['personal_bereavement'] or 'not established'}",
                   f"- **Dates / context:** {r['dates_context'] or 'unknown'}",
                   f"- **Population evidence:** {r['population_evidence']}",
                   f"- **Data licence / access:** {r['license'] or 'none stated'}",
                   f"- **Restrictions:** {r['restrictions'] or 'none recorded'}",
                   f"- **Authentication / payment:** {r['auth_or_payment'] or 'none'}",
                   *([f"- **Suitability:** {r['suitability']}"] if r["suitability"] else []),
                   *([f"- **Limitations:** {r['limitations']}"] if r["limitations"] else []),
                   f"- **Inspection depth:** {r['inspected']} - **Evidence:** `{r['evidence_file']}`", ""]
    if problems:
        md += ["## Register build warnings", ""] + [f"- {p}" for p in problems]
    (DOCS / "source_register.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"{len(rows)} rows -> docs/source_register.csv, docs/source_register.md")
    print(dict(sc))
    for p in problems:
        print("WARNING:", p)


if __name__ == "__main__":
    build()
