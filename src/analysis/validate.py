"""Channel validation against the adjudicated gold set: coder alpha, per-value precision / recall / F1, rae.py inputs."""
import argparse
import csv
from collections import defaultdict
from pathlib import Path

from agreement import alpha_nominal, canon
from gold import CODEBOOK

ROOT = Path(__file__).resolve().parents[2]
COLUMNS = ["channel", "field", "value", "lang", "n_items", "tp", "fp", "fn", "tn", "precision", "recall", "f1",
           "measure", "sensitivity", "fpr", "n_pos", "n_neg", "status"]


def read_sheet(path):
    with open(path, encoding="utf-8", newline="") as fh:
        return {r["gold_id"]: r for r in csv.DictReader(fh)}


def ratio(a, b):
    return round(a / b, 4) if b else ""


def score(gold, pred, field, lang):
    items = [(canon(g.get(field), field), canon(pred.get(gid, {}).get(field), field))
             for gid, g in gold.items() if lang in ("all", g.get("lang")) and canon(g.get(field), field)]
    rows = []
    for v in CODEBOOK[field]:
        tp = sum(1 for g, p in items if g == v and p == v)
        fn = sum(1 for g, p in items if g == v and p != v)
        fp = sum(1 for g, p in items if g != v and p == v)
        tn = len(items) - tp - fn - fp
        if tp + fn + fp == 0:
            continue
        prec, rec = ratio(tp, tp + fp), ratio(tp, tp + fn)
        f1 = ratio(2 * tp, 2 * tp + fp + fn)
        rows.append(dict(field=field, value=v, lang=lang, n_items=len(items), tp=tp, fp=fp, fn=fn, tn=tn,
                         precision=prec, recall=rec, f1=f1, sensitivity=rec, fpr=ratio(fp, fp + tn),
                         n_pos=tp + fn, n_neg=fp + tn))
    return rows


def coder_alpha(c1, c2):
    out = []
    for field in CODEBOOK:
        for lang in ("hi", "en", "all"):
            pairs = [(canon(a.get(field), field), canon(c2[g].get(field), field))
                     for g, a in c1.items() if g in c2 and lang in ("all", a.get("lang"))]
            both = sum(1 for a, b in pairs if a and b)
            al = alpha_nominal(pairs) if pairs else float("nan")
            out.append(dict(field=field, lang=lang, n_both_coded=both,
                            alpha_nominal="" if al != al else round(al, 3)))
    return out


def table3(rows, alpha, status, channels, n_gold):
    md = [f"# Table 3. Validation of the coding channels against the adjudicated gold set", "",
          f"**Status: {status}.** Gold items: {n_gold}. Generated by `src/analysis/validate.py`; numbers come from "
          "`results/validation_table.csv`.", ""]
    md += ["## 3a. Inter-coder agreement (Krippendorff's alpha, nominal)", ""]
    if alpha:
        md += ["| field | hi | en | all | items coded by both (all) |", "|---|---|---|---|---|"]
        by = {(a["field"], a["lang"]): a for a in alpha}
        for f in CODEBOOK:
            md.append(f"| {f} | {by[f, 'hi']['alpha_nominal'] or '—'} | {by[f, 'en']['alpha_nominal'] or '—'} | "
                      f"{by[f, 'all']['alpha_nominal'] or '—'} | {by[f, 'all']['n_both_coded']} |")
    else:
        md.append("No coder sheets given.")
    md += ["", "## 3b. Macro-F1 per channel (values with at least one gold item)", ""]
    head = "| field | " + " | ".join(f"{c} hi | {c} en" for c in channels) + " |"
    md += [head, "|---|" + "---|" * (2 * len(channels))]
    for f in CODEBOOK:
        cells = []
        for c in channels:
            for lang in ("hi", "en"):
                f1s = [r["f1"] for r in rows if r["channel"] == c and r["field"] == f and r["lang"] == lang
                       and r["n_pos"] > 0 and r["f1"] != ""]
                cells.append(f"{sum(f1s) / len(f1s):.2f}" if f1s else "—")
        md.append(f"| {f} | " + " | ".join(cells) + " |")
    md += ["", "## 3c. Per value (sensitivity = recall; FPR = false-positive rate; these feed rae.py)", "",
           "| channel | field | value | lang | gold n | P | R | F1 | FPR |", "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        if r["lang"] != "all":
            md.append(f"| {r['channel']} | {r['field']} | {r['value']} | {r['lang']} | {r['n_pos']} | "
                      f"{r['precision']} | {r['recall']} | {r['f1']} | {r['fpr']} |")
    return "\n".join(md) + "\n"


def write_csv(path, rows, columns):
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=columns)
        w.writeheader()
        w.writerows(rows)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--gold", required=True)
    ap.add_argument("--coders", nargs=2, metavar=("C1", "C2"))
    ap.add_argument("--channel", action="append", default=[], metavar="NAME=PATH", required=True)
    ap.add_argument("--status", required=True)
    ap.add_argument("--out", default=str(ROOT / "results/validation_table.csv"))
    ap.add_argument("--alpha-out", default=str(ROOT / "results/validation_alpha.csv"))
    ap.add_argument("--md", default=str(ROOT / "results/table3_validation.md"))
    args = ap.parse_args(argv)

    gold = read_sheet(args.gold)
    channels = {}
    for spec in args.channel:
        name, path = spec.split("=", 1)
        channels[name] = read_sheet(path)
        missing = set(gold) - set(channels[name])
        if missing:
            print(f"WARNING {name}: {len(missing)} gold items without a prediction (counted as misses)")
    rows = []
    for name, pred in channels.items():
        for field in CODEBOOK:
            for lang in ("hi", "en", "all"):
                for r in score(gold, pred, field, lang):
                    rows.append(dict(channel=name, measure=f"{name}:{field}={r['value']}", status=args.status, **r))
    alpha = coder_alpha(read_sheet(args.coders[0]), read_sheet(args.coders[1])) if args.coders else []
    write_csv(args.out, rows, COLUMNS)
    write_csv(args.alpha_out, alpha, ["field", "lang", "n_both_coded", "alpha_nominal"])
    Path(args.md).write_text(table3(rows, alpha, args.status, list(channels), len(gold)), encoding="utf-8")
    print(f"{len(rows)} rows -> {args.out}; alpha rows {len(alpha)} -> {args.alpha_out}; Table 3 -> {args.md}")


if __name__ == "__main__":
    main()
