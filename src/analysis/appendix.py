import csv
import hashlib
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gold import components_list

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "appendix"
LEX = ROOT / "lexicon"
SOURCES = {"A": [LEX / "components.csv", LEX / "entry_vectors.csv"], "B": [LEX / "lexicon.csv", LEX / "molecules.csv"],
           "C": [ROOT / "data" / "processed" / "predicate_inventory.csv"], "D": [LEX / "primes.csv"],
           "E": [ROOT / "tests" / "flag_sentences.csv"]}


def read(path):
    with open(path, encoding="utf-8", newline="") as fh:
        return list(csv.DictReader(fh))


def cell(v):
    return " / ".join(x.strip() for x in str(v or "").replace("|", "\\|").splitlines() if x.strip()) or "—"


def table(header, rows):
    return "\n".join(["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
                     + ["| " + " | ".join(cell(c) for c in r) + " |" for r in rows])


def head(letter, title, note):
    srcs = ", ".join(f"`{p.relative_to(ROOT)}` (sha256 `{hashlib.sha256(p.read_bytes()).hexdigest()[:16]}…`)"
                     for p in SOURCES[letter])
    return [f"# Appendix {letter}. {title}", "", f"Generated by `src/analysis/appendix.py` from {srcs}. Do not edit by "
            "hand.", "", note, ""]


def a_components():
    comps = components_list(LEX)
    rows = {r["component_id"]: r for r in read(LEX / "components.csv")}
    body = [[c, rows[c]["gloss_primes"], rows[c].get("example_hi", ""), rows[c].get("example_en", ""),
             rows[c]["n_entries_hi"], rows[c]["n_entries_en"]] for c in comps]
    return head("A", f"Component inventory (K = {len(comps)})",
                "The fixed inventory of semantic components, each one line of prime-language meaning; one constructed "
                "example per language (the lexicon's own).") + \
        [table(["Component", "Gloss in primes", "Example (Hindi)", "Example (English)", "Hindi entries",
                "English entries"], body)]


def b_lexicon():
    from translation_bias import native_only_entries
    lex = read(LEX / "lexicon.csv")
    native = native_only_entries(read(LEX / "molecules.csv"), lex)
    body = [[e["entry_id"], e["lang"], e["headword_deva"] if e["lang"] == "hi" else e["headword_en"],
             e["nsm_explication"], e["component_vector"], e["orientation"], e["process"],
             "yes" if e["entry_id"] in native else ("—" if e["lang"] == "en" else "no")] for e in lex]
    return head("B", f"Lexicon ({len(lex)} entries)",
                "Native-only (Hindi entries): the explication needs a molecule no English entry uses (strict "
                "definition, decided 2026-10-10). Orientation I individual / F familial / C communal / R ritual; "
                "process L loss / Rs restoration. Example sentences are not reproduced here.") + \
        [table(["Entry", "Lang", "Headword", "NSM explication", "Components", "Orientation", "Process", "Native-only"],
               body)]


def c_rules():
    inv = read(ROOT / "data" / "processed" / "predicate_inventory.csv")
    body = [[r["predicate"], r["lang"], r["site"], r["decision"], r["rule_id"], r["twin"], r["alternative"],
             r["source"], r["equivalent"]] for r in inv]
    return head("C", f"Eligibility rule table ({len(inv)} predicate keys)",
                "Every predicate key the eligibility detector decides on (eligibility.py rule tables plus the corpus "
                "predicates it met), with its decision (forced / chosen / review / NA), the rule, the twin "
                "construction that makes a site a choice, and the cross-language equivalent. Predicate keys are "
                "lemmas, not text.") + \
        [table(["Predicate", "Lang", "Site", "Decision", "Rule", "Twin", "Alternative", "Source", "Equivalent"], body)]


def d_exponents():
    pr = read(LEX / "primes.csv")
    body = [[r["prime_en"], r["hindi_exponent"], r["hindi_roman"], r["allolexes"], r["group"], r["status"],
             r["confidence"]] for r in pr]
    return head("D", f"NSM prime exponents in Hindi ({len(pr)} primes)",
                "Exponent, transliteration and allolexes of each semantic prime, with its verification status and "
                "confidence (canonical-context substitution; test sentences in lexicon/primes.csv).") + \
        [table(["Prime", "Hindi exponent", "Roman", "Allolexes", "Group", "Status", "Confidence"], body)]


def e_flags():
    fl = read(ROOT / "tests" / "flag_sentences.csv")
    body = [[k + 1, r["lang"], r["sentence"], r["expected_flags"] or "(none)"] for k, r in enumerate(fl)]
    return head("E", f"Construction-flag test set ({len(fl)} sentences)",
                "Hand-written sentences with traps (a dative that is not an experiencer, a converb, literal motion, a "
                "lower-case 'rip'), run before every build (tests/test_flags.py). Constructed, not corpus text.") + \
        [table(["#", "Lang", "Sentence", "Expected flags"], body)]


FILES = {"A_component_inventory.md": a_components, "B_lexicon.md": b_lexicon, "C_rule_table.md": c_rules,
         "D_exponent_table.md": d_exponents, "E_flag_test_set.md": e_flags}


def build():
    return {name: "\n".join(fn()) + "\n" for name, fn in FILES.items()}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in build().items():
        (OUT / name).write_text(text, encoding="utf-8")
        print(f"wrote {OUT / name} ({text.count(chr(10)) - 8} table rows)")


if __name__ == "__main__":
    main()
