"""Code appendix: the four scripts behind the headline estimates, verbatim, with headers, in docs/code_appendix.md."""
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FILES = [
    ("src/analysis/decompose.py", "python", "Output 3: decomposition of the Hindi − English gap (forced, opportunity, "
                                             "choice) with the text bootstrap and the drop-largest-text sensitivity",
     ["src/analysis/gold.py (split_of)"]),
    ("R/h1_glmm.R", "r", "Outputs 3 and 4: relational ~ hindi + log clauses + loss type + (1 | text), Runs 1, 2, 2b "
                         "and R-F6; GLMM and CR2 cluster-robust GLM",
     ["R/common.R (arguments, agreement guard, inputs)"]),
    ("src/analysis/corrected_rates.py", "python", "Output 2: Rogan–Gladen corrected rates of the dictionary channel "
                                                  "per category and language, double bootstrap",
     ["src/analysis/rae.py (estimator)", "src/analysis/predictions.py (tests_allowed)", "src/analysis/gold.py"]),
    ("R/audit.R", "r", "Output 5: recognition model per system, cue interaction, stability selection of under-read "
                       "components", ["R/common.R (arguments, agreement guard, inputs)"]),
]
HELPERS = [("R/common.R", "r", "Shared R helpers (sourced by h1_glmm.R and audit.R)", []),
           ("src/analysis/rae.py", "python", "Rogan–Gladen estimator (imported by corrected_rates.py)", [])]


def fence(text):
    longest = run = 0
    for ch in text:
        run = run + 1 if ch == "`" else 0
        longest = max(longest, run)
    return "`" * max(3, longest + 1)


def render(files, root=ROOT):
    out = ["# Code appendix", "",
           "Generated by `src/analysis/code_appendix.py`; regenerate, do not edit by hand. Each script is reproduced "
           "verbatim; the sha256 identifies the exact file. All features these scripts read are machine-provisional "
           "(no human-validated labels) until the gold-set agreement statistics exist.", "", "## Contents", ""]
    out += [f"{i}. [{path}](#{i}-{anchor(path)})" for i, (path, *_rest) in enumerate(files, 1)]
    for i, (path, lang, role, deps) in enumerate(files, 1):
        data = (root / path).read_bytes()
        text = data.decode("utf-8")
        f = fence(text)
        out += ["", f"## {i}. {path}", "", f"- Role: {role}",
                f"- Lines: {text.count(chr(10)) + (0 if text.endswith(chr(10)) else 1)}",
                f"- sha256: `{hashlib.sha256(data).hexdigest()}`"]
        if deps:
            out.append("- Uses (not reproduced here): " + "; ".join(f"`{d}`" for d in deps))
        out += ["", f + lang, text.rstrip("\n"), f]
    return "\n".join(out) + "\n"


def anchor(path):
    return "".join(c for c in path.lower() if c.isalnum() or c in "-_ ").replace(" ", "-")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", default=str(ROOT / "docs" / "code_appendix.md"))
    ap.add_argument("--with-helpers", action="store_true", help="also reproduce R/common.R and rae.py")
    args = ap.parse_args(argv)
    files = FILES + (HELPERS if args.with_helpers else [])
    Path(args.out).write_text(render(files), encoding="utf-8")
    print(f"{len(files)} files -> {args.out}")


if __name__ == "__main__":
    main()
